"""
Таблица "название цвета (RU) -> HEX-код" для отображения цветовых свотчей
в фильтрах каталога. Ключи нормализованы (нижний регистр, ё->е), чтобы
сравнение не зависело от регистра/буквы ё, как и остальная логика фильтра
по цвету в product.py.
"""

COLOR_HEX_MAP = {
    "бордовый": "#7c1a2e",
    "голубой": "#4fa8d8",
    "желтый": "#f2d94e",
    "изумрудный": "#1c7a4a",
    "коричневый": "#6b4423",
    "красный": "#c0392b",
    "лимонный": "#e8e64a",
    "малиновый": "#c2185b",
    "молочный": "#f5f0e6",
    "пудровый": "#f0c9c9",
    "светло-серый": "#c8c8c8",
    "серый": "#808080",
    "сиреневый": "#b19cd9",
    "терракотовый": "#c1662e",
    "темно-красный": "#7a1414",
    "темно-серый": "#4a4a4a",
    "темно-синий": "#1a2a5e",
    "фиолетовый": "#7c3fa8",
    "хаки": "#8a8a5c",
    "черный": "#1a1a1a",
    "синий": "#2255bb",
}

FALLBACK_HEX = "#999999"


def get_color_hex(color_name: str) -> str:
    normalized = color_name.strip().lower().replace("ё", "е")
    return COLOR_HEX_MAP.get(normalized, FALLBACK_HEX)
